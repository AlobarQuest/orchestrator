"""A rotation's decomposition, generated from its registered intake (ADR-0055 amendment 15,
increment 5).

The plan a unit runs is the one its approved package's criteria describe (`plans.select_plan`), so
the decomposition is that plan, read the same way the executor reads it: one unit per machine
segment, each criterion mapped to the unit holding its step. Each envelope is exactly what the
orchestrator's rotation pattern (`rotation_known_good`) recognises, so no unit needs an authority
click of its own; `host_without_overlap`, the one declaration only a person makes, is never
generated.

Only a derived plan is generated. A package still describing its type's pre-derivation plan names
a plan this lane can't read without importing a provider, so it is refused with that reason.
"""

from __future__ import annotations

from collections.abc import Mapping, Sequence
from typing import Any, Final

from rotation_worker.contract import ContractError, Plan, UnitPlan
from rotation_worker.destinations import same
from rotation_worker.envelope import NON_HOSTED_KEY
from rotation_worker.plans import derive, select_plan, writes_hosted_service
from rotation_worker.registry import RegistryEntry
from rotation_worker.types import CLASS_TYPES, TYPES

PACKAGE_PREFIX: Final = "rotation-"
CAPABILITY: Final = "operational_action"
MAX_ATTEMPTS: Final = 3


class DecomposeError(RuntimeError):
    """The intake can't be decomposed by machine; the reason says what a person does instead."""


def credential_of(package_id: str) -> str | None:
    return (
        package_id.removeprefix(PACKAGE_PREFIX) if package_id.startswith(PACKAGE_PREFIX) else None
    )


def decomposition(intake: Mapping[str, Any], entry: RegistryEntry) -> dict[str, Any]:
    """The proposal body for a rotation intake: its units, their order and its criteria's units.

    `intake` is `GET /package-intakes/{id}`; `entry` is the credential's registry row.
    """
    package_id = str(intake.get("package_id"))
    credential = credential_of(package_id)
    if credential is None or entry.credential.get("id") != credential:
        raise DecomposeError(f"{package_id} is no standing rotation package of this credential")
    if not entry.rotated_by_sds:
        raise DecomposeError(f"the registry doesn't hand {credential} to the SDS (rotated_by_sds)")
    adapter = CLASS_TYPES.get(str(entry.credential.get("class")))
    if adapter is None:
        raise DecomposeError(f"{credential}'s class names no type the SDS rotates")
    declared = TYPES[adapter]
    derived = derive(declared.capabilities, entry.destinations, entry.keeper, declared.store_kind)
    criteria = _criteria(intake)
    try:
        plan = select_plan(
            (derived,), [{"id": ac, "evidence": text} for ac, (_, text) in criteria.items()]
        )
    except ContractError:
        raise DecomposeError(
            f"{package_id}'s criteria describe its type's pre-derivation plan, not the derived "
            "one: revise the package onto the derived plan, or decompose it by hand"
        ) from None
    destinations = _destinations(intake)
    if not same(destinations, entry.destinations):
        # The executor refuses every unit whose envelope, package and registry disagree, and an
        # approved envelope can't change: propose nothing, and let the next revision carry them.
        raise DecomposeError(
            f"{package_id}'s destinations differ from the registry's: the proposer revises it at "
            "its next rotation, or a person decomposes this one by hand"
        )
    units = [segment for segment in plan.segments if isinstance(segment, UnitPlan)]
    keys = [f"{credential}-{unit.name}" for unit in units]
    return {
        "rationale": (
            f"The {adapter} type's plan derived for {credential} (ADR-0055 amendment 15), "
            "generated by rotation-decomposer from the approved package's criteria. A person's "
            "acts are "
            "announced and observed by the executor, so none is a dependency."
        ),
        "proposed_units": [
            _unit(key, credential, adapter, plan, unit, destinations)
            for key, unit in zip(keys, units, strict=True)
        ],
        "dependencies": [
            {
                "source_unit_key": later,
                "kind": "work_unit",
                "target_unit_key": earlier,
                "required_state_or_condition": "completed",
            }
            for earlier, later in zip(keys, keys[1:], strict=False)
        ],
        "ac_mappings": [
            {"ac_id": criteria[step.ac_id][0], "unit_key": key}
            for key, unit in zip(keys, units, strict=True)
            for step in unit.steps
            if step.ac_id is not None
        ],
        "retained_acs": [],
    }


def _criteria(intake: Mapping[str, Any]) -> dict[str, tuple[str, str]]:
    """Each criterion's `AC-…` id, mapped to its database id and its evidence text."""
    found: dict[str, tuple[str, str]] = {}
    for row in intake.get("acceptance_criteria") or []:
        if not isinstance(row, Mapping):
            raise DecomposeError("an acceptance criterion isn't an object")
        ac_id, database_id, evidence = row.get("ac_id"), row.get("id"), row.get("evidence")
        if not all(isinstance(value, str) for value in (ac_id, database_id, evidence)):
            raise DecomposeError("an acceptance criterion lacks its id, database id or evidence")
        found[str(ac_id)] = (str(database_id), str(evidence))
    return found


def _destinations(intake: Mapping[str, Any]) -> list[str]:
    snapshot = intake.get("enforcement_snapshot")
    fields = snapshot.get("profile_fields") if isinstance(snapshot, Mapping) else None
    listed = fields.get("destinations") if isinstance(fields, Mapping) else None
    if not isinstance(listed, list) or not all(isinstance(d, str) for d in listed):
        raise DecomposeError("the intake carries no destination list")
    return listed


def _unit(
    key: str,
    credential: str,
    adapter: str,
    plan: Plan,
    unit: UnitPlan,
    destinations: Sequence[str],
) -> dict[str, Any]:
    constraints: dict[str, Any] = {
        "rotation_adapter": adapter,
        "rotation_unit": unit.name,
        "destinations": list(destinations),
    }
    if not writes_hosted_service(destinations, plan, unit):
        constraints[NON_HOSTED_KEY] = True
    steps = ", ".join(step.kind.value for step in unit.steps)
    return {
        "unit_key": key,
        "title": f"{credential}: {unit.name}",
        "outcome": f"the {unit.name} unit's steps ({steps}) complete, each with its evidence",
        "required_capability": CAPABILITY,
        "authority": {
            "capabilities": {CAPABILITY: "allowed"},
            "budgets": {"max_attempts": MAX_ATTEMPTS, "max_llm_calls": None},
            "change_class": None,
            "conformance": None,
            "constraints": constraints,
        },
        "max_attempts": MAX_ATTEMPTS,
    }
